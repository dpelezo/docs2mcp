def _text(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, list):
        return ",".join(_text(item) for item in value)  # pyright: ignore[reportUnknownVariableType]
    return str(value)


def _auth(headers: dict[str, str], query: dict[str, str]) -> None:
    del headers, query  # the API needs no credentials


def _choose(tool: str, given: dict[str, Any]) -> tuple[Route, list[str]]:
    """The route for these arguments, and any given argument it cannot take.

    Of the routes whose required arguments are all given, the first that takes
    every given argument wins; failing that, the one that takes the most.
    """
    usable = [r for r in ROUTES[tool] if all(name in given for name in r["requires"])]
    if not usable:
        options = " or ".join(", ".join(r["requires"]) or "nothing" for r in ROUTES[tool])
        raise ToolError(f"{tool} needs one of these argument sets: {options}")
    unused = [[name for name in given if name not in r["arguments"]] for r in usable]
    best = min(range(len(usable)), key=lambda index: len(unused[index]))
    return usable[best], unused[best]


def call(tool: str, arguments: dict[str, Any]) -> str:
    """Pick the route for these arguments, call it, and return the response as text."""
    given = {name: value for name, value in arguments.items() if value is not None}
    route, unused = _choose(tool, given)
    path = route["path"]
    query: dict[str, str] = {}
    headers: dict[str, str] = {"User-Agent": USER_AGENT, "Accept": "application/json"}
    body: dict[str, Any] = {}
    values = [
        (*route["arguments"][name], value)
        for name, value in given.items()
        if name in route["arguments"]
    ]
    for name, location, value in [*values, *route["constants"]]:
        if location == "path":
            path = path.replace("{" + name + "}", quote(_text(value), safe=""))
        elif location == "query":
            query[name] = _text(value)
        elif location == "header":
            headers[name] = _text(value)
        else:
            body[name] = value
    _auth(headers, query)

    try:
        with httpx.Client(
            base_url=BASE_URL, timeout=TIMEOUT_SECONDS, transport=transport
        ) as client:
            response = client.request(
                route["method"], path, params=query, headers=headers, json=body or None
            )
            response = _follow(client, response)
    except httpx.HTTPError as error:
        raise ToolError(f"{route['method']} {path} failed: {error}") from error
    if response.is_error:
        raise ToolError(
            f"{route['method']} {path} returned HTTP {response.status_code}: {response.text[:500]}"
        )
    try:
        text = _fit(response.json())
    except ValueError:
        kind = response.headers.get("content-type", "unknown")
        text = _cut(f"[The response is {kind}, not JSON]\n{response.text}")
    if unused:
        text += f"\n[Not used by {route['method']} {route['path']}: {', '.join(unused)}.]"
    return text


def _follow(client: httpx.Client, response: httpx.Response) -> httpx.Response:
    """Follow redirects on the API's own host, up to MAX_REDIRECTS.

    A redirect to another host is refused, so headers such as an API key never
    leave the API. Open Library's /isbn/ answers with a redirect, for example.
    """
    home = httpx.URL(BASE_URL).host
    for _ in range(MAX_REDIRECTS):
        target = response.next_request
        if target is None:
            return response
        if target.url.host != home:
            raise ToolError(f"The API redirected to another host, {target.url.host}; not followed")
        response = client.send(target)
    if response.next_request is not None:
        raise ToolError(f"More than {MAX_REDIRECTS} redirects; stopped")
    return response


def _cut(text: str) -> str:
    """The text, cut to MAX_RESULT_CHARS with a note if it is longer."""
    if len(text) <= MAX_RESULT_CHARS:
        return text
    note = f"[Cut to {MAX_RESULT_CHARS} of {len(text)} characters. Narrow the request.]"
    return f"{text[:MAX_RESULT_CHARS]}\n{note}"


def _fit(value: Any) -> str:
    """JSON text of a response, made to fit MAX_RESULT_CHARS by halving what is biggest.

    The biggest list loses its last half, or the biggest nested object its last
    half of keys, until the text fits. The top-level object keeps every key, so
    a field after a long list is still shown. A note after the JSON says what was
    left out. If that is not enough, the text is cut.
    """
    text = json.dumps(value, ensure_ascii=False)
    full = len(text)
    holder: dict[str, Any] = {"": value}
    dropped: dict[str, list[int]] = {}
    while len(text) > MAX_RESULT_CHARS:
        found: list[tuple[int, Any, Any, str]] = []
        _measure(holder, "", found)
        if not found:
            break
        _, parent, key, path = max(found, key=lambda item: item[0])
        child = parent[key]
        counts = dropped.setdefault(path, [0, 0])
        if isinstance(child, list):
            items = cast("list[Any]", child)
            counts[0] += len(items) - len(items) // 2
            parent[key] = items[: len(items) // 2]
        else:
            pairs = list(cast("dict[str, Any]", child).items())
            counts[1] += len(pairs) - len(pairs) // 2
            parent[key] = dict(pairs[: len(pairs) // 2])
        text = json.dumps(holder[""], ensure_ascii=False)
    if not dropped or len(text) > MAX_RESULT_CHARS:
        return _cut(text)
    parts: list[str] = []
    for path, (items, keys) in dropped.items():
        lost = [f"{n:,} {unit} not shown" for n, unit in ((items, "items"), (keys, "keys")) if n]
        parts.append(f"{path or 'the response'}: {' and '.join(lost)}")
    left_out = "; ".join(parts)
    note = (
        f"[Shortened to fit {MAX_RESULT_CHARS:,} of {full:,} characters by keeping the first "
        f"part of the biggest lists and objects ({left_out}). Narrow the request to see more.]"
    )
    return f"{text}\n{note}"


def _measure(node: Any, path: str, found: list[tuple[int, Any, Any, str]]) -> int:
    """About how many characters node takes as JSON.

    Lists and nested objects with 2 or more entries go into found; the top-level
    object (path "") does not, so its keys are never dropped.
    """
    parent: Any = node
    children: list[tuple[Any, str, Any]]
    if isinstance(node, dict):
        children = [
            (key, f"{path}.{key}" if path else key, child)
            for key, child in cast("dict[str, Any]", node).items()
        ]
    elif isinstance(node, list):
        children = [
            (index, f"{path}[]", child) for index, child in enumerate(cast("list[Any]", node))
        ]
    else:
        return len(json.dumps(node, ensure_ascii=False))
    size = 2
    for key, child_path, child in children:
        child_size = _measure(child, child_path, found)
        size += child_size + len(str(key)) + 4
        is_list = isinstance(child, list) and len(cast("list[Any]", child)) > 1
        is_nested = isinstance(child, dict) and bool(child_path) and len(cast("Any", child)) > 1
        if is_list or is_nested:
            found.append((child_size, parent, key, child_path))
    return size


